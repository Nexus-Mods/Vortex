const hashFile = async (filePath: string) => checksum(await readFile(filePath));
const pluginsTxt = Buffer.from("# Automatically generated by Vortex\r\n*Café.esp\r\n", "latin1");

const plannedRuns = () =>
  vi
    .mocked(window.api)
    .log.mock.calls.filter((call) => call[1] === "planner operations")
    .map((call) => JSON.parse(String(call[2])) as { diskEntries: number });

async function makeResolvableGame() {
  const game = await makeDeployedGame({
    methodId: "hardlink_activator",
    extraReducers: [{ path: ["session", "mods"], reducer: sessionReducer }],
  });
  // a store whose install carries no ids, so no store library is scanned
  game.setState((draft) => {
    draft.settings.gameMode.discovered[game.gameId].store = "epic";
  });
  return game;
}

test("a contributed file joins the lockfile with its hash", async () => {
  const game = await makeResolvableGame();
  const destinationPath = path.join(game.dataPath, "plugins.txt");
  const contributions = new LockfileContributions();
  contributions.register(
    "plugin-lists",
    () => true,
    () => Promise.resolve([{ destinationPath, content: pluginsTxt }]),
  );

  const lockfile = await resolveLockfile(
    game.api,
    VortexGameId(game.gameId),
    contributions,
    hashFile,
  );

  expect(lockfile.files).toEqual([
    makeGeneratedFileSource({
      destinationPath: toPortablePath(destinationPath),
      fileHash: checksum(pluginsTxt),
    }),
  ]);
});

test("a contribution is asked for the game and profile being resolved", async () => {
  const game = await makeResolvableGame();
  const generate = vi.fn<LockfileContribution>(() => Promise.resolve<IGeneratedFile[]>([]));
  const condition = vi.fn<LockfileContributionCondition>(() => true);
  const contributions = new LockfileContributions();
  contributions.register("plugin-lists", condition, generate);

  await resolveLockfile(game.api, VortexGameId(game.gameId), contributions, hashFile);

  expect(condition).toHaveBeenCalledWith(expect.anything(), game.gameId);
  expect(generate).toHaveBeenCalledWith(expect.anything(), game.gameId, game.profileId);
});

test("a plan after deployments sees the deployment targets as they were before the first", async () => {
  const game = await makeResolvableGame();
  const removedPath = QualifiedPath.fromNative(path.join(game.dataPath, "removed.esp"));
  const disk = installInMemoryFS((builder) =>
    builder.file(removedPath, { type: "text", data: "removed" }),
  );
  vi.mocked(window.api).log.mockClear();
  const sortPlugins = () => game.api.events.emit("did-sort-plugins", game.gameId);
  try {
    registerResolveLockFile(game.api, hashFile);
    await game.emitAndAwait("will-deploy", game.profileId);
    await game.emitAndAwait("did-deploy", game.profileId, {});
    sortPlugins();
    await vi.waitFor(() => expect(plannedRuns()).toHaveLength(1));

    await game.emitAndAwait("will-deploy", game.profileId);
    await disk.fs.delete(removedPath);
    await game.emitAndAwait("will-deploy", game.profileId);
    await game.emitAndAwait("did-deploy", game.profileId, {});
    sortPlugins();

    await vi.waitFor(() => expect(plannedRuns()).toHaveLength(2));
    const [beforeDeployment, afterDeployment] = plannedRuns();
    expect(afterDeployment.diskEntries).toBe(beforeDeployment.diskEntries);
  } finally {
    disk.restore();
  }
});

const MOD_ID = VortexModId("mod");

/** A game with one staged mod, mod.esp, enabled and deployed when `enabled`. */
async function makeGameWithStagedMod(enabled: boolean) {
  const game = await makeResolvableGame();
  const mod = makeStagedMod(MOD_ID);
  const stagedPath = path.join(game.stagingPath, mod.installationPath, "mod.esp");
  const deployedPath = path.join(game.dataPath, "mod.esp");
  // the resolver lists staging through window.api.fs and hashes it from the disk
  await writeInto(path.dirname(stagedPath), "mod.esp");
  const disk = installInMemoryFS((builder) => {
    builder.file(QualifiedPath.fromNative(stagedPath), { type: "text", data: "mod" });
    builder.dir(QualifiedPath.fromNative(game.dataPath));
    if (enabled) {
      builder.file(QualifiedPath.fromNative(deployedPath), { type: "text", data: "mod" });
    }
  });
  game.setState((draft) => {
    draft.persistent.mods[game.gameId] = { [MOD_ID]: mod };
    draft.persistent.profiles[game.profileId].modState = { [MOD_ID]: makeProfileMod({ enabled }) };
  });
  return { game, disk, deployedPath, mod };
}

const plannedOperations = () =>
  vi
    .mocked(window.api)
    .log.mock.calls.filter((call) => call[1] === "planner operations ")
    .map((call) => JSON.parse(String(call[2])) as { operation: string; path: string });

test("a removed mod's files plan an unlink after the deployment that follows", async () => {
  const { game, disk, deployedPath } = await makeGameWithStagedMod(true);
  vi.mocked(window.api).log.mockClear();
  const sortPlugins = () => game.api.events.emit("did-sort-plugins", game.gameId);
  try {
    registerResolveLockFile(game.api, hashFile);
    await game.emitAndAwait("will-deploy", game.profileId);
    await game.emitAndAwait("did-deploy", game.profileId, {});
    sortPlugins();
    await vi.waitFor(() => expect(plannedRuns()).toHaveLength(1));

    await game.emitAndAwait("will-remove-mods", game.gameId, [MOD_ID]);
    await disk.fs.delete(QualifiedPath.fromNative(deployedPath));
    game.setState((draft) => {
      delete draft.persistent.mods[game.gameId][MOD_ID];
    });
    await game.emitAndAwait("will-deploy", game.profileId);
    await game.emitAndAwait("did-deploy", game.profileId, {});
    sortPlugins();

    await vi.waitFor(() => expect(plannedRuns()).toHaveLength(2));
    expect(plannedOperations()).toContainEqual({
      operation: "UNLINK",
      path: toPortablePath(deployedPath),
    });
  } finally {
    disk.restore();
  }
});

test("a mod deployed on its own plans a link without a backup", async () => {
  const { game, disk, deployedPath } = await makeGameWithStagedMod(false);
  vi.mocked(window.api).log.mockClear();
  const sortPlugins = () => game.api.events.emit("did-sort-plugins", game.gameId);
  try {
    registerResolveLockFile(game.api, hashFile);
    await game.emitAndAwait("will-deploy", game.profileId);
    await game.emitAndAwait("did-deploy", game.profileId, {});
    sortPlugins();
    await vi.waitFor(() => expect(plannedRuns()).toHaveLength(1));

    game.setState((draft) => {
      draft.persistent.profiles[game.profileId].modState[MOD_ID].enabled = true;
    });
    await game.emitAndAwait("will-deploy-single-mod", game.gameId, MOD_ID, true);
    await disk.fs.writeFile(
      QualifiedPath.fromNative(deployedPath),
      new TextEncoder().encode("mod"),
    );
    await game.emitAndAwait("will-deploy", game.profileId);
    await game.emitAndAwait("did-deploy", game.profileId, {});
    sortPlugins();

    await vi.waitFor(() => expect(plannedRuns()).toHaveLength(2));
    const portablePath = toPortablePath(deployedPath);
    expect(plannedOperations().filter(({ path }) => path === portablePath)).toEqual([
      { operation: "LINK", path: portablePath },
    ]);
  } finally {
    disk.restore();
  }
});

test("a sort before the deployment leaves pending changes to the deployment's plan", async () => {
  const { game, disk, deployedPath } = await makeGameWithStagedMod(true);
  try {
    registerResolveLockFile(game.api, hashFile);
    await game.emitAndAwait("will-deploy", game.profileId);
    await game.emitAndAwait("did-deploy", game.profileId, {});
    await game.emitAndAwait("did-sort-plugins", game.gameId);

    await game.emitAndAwait("will-remove-mods", game.gameId, [VortexModId("other")]);
    game.setState((draft) => {
      draft.persistent.profiles[game.profileId].modState[MOD_ID].enabled = false;
    });
    await game.emitAndAwait("did-sort-plugins", game.gameId);

    vi.mocked(window.api).log.mockClear();
    await game.emitAndAwait("will-deploy", game.profileId);
    await disk.fs.delete(QualifiedPath.fromNative(deployedPath));
    await game.emitAndAwait("did-deploy", game.profileId, {});
    await game.emitAndAwait("did-sort-plugins", game.gameId);

    expect(plannedOperations()).toContainEqual({
      operation: "UNLINK",
      path: toPortablePath(deployedPath),
    });
  } finally {
    disk.restore();
  }
});

/** Deploys as a deployment does, up to the plugin sort that follows it. */
async function deploy(game: IDeployedGameHarness) {
  await game.emitAndAwait("will-deploy", game.profileId);
  await game.emitAndAwait("did-deploy", game.profileId, {});
}

test("a plan run reports its figures for its game, without paths", async () => {
  const { game, disk, deployedPath } = await makeGameWithStagedMod(true);
  vi.mocked(emitPlannerPlanEvent).mockClear();
  try {
    registerResolveLockFile(game.api, hashFile);
    await deploy(game);
    await game.emitAndAwait("did-sort-plugins", game.gameId);

    const [, gameId, figuresOf] = vi.mocked(emitPlannerPlanEvent).mock.calls[0];
    expect(gameId).toBe(game.gameId);
    const figures = figuresOf();
    expect(figures).toMatchObject({
      lockfile_files: 1,
      generated_files: 0,
      disk_entries: 1,
      scan_roots: 1,
      operations: { backup: 1, link: 1, unlink: 0 },
    });
    expect(figures.resolve_ms).toBeDefined();
    const sent = JSON.stringify(figures);
    expect(sent).not.toMatch(/[\\/]/);
    expect(sent).not.toContain(QualifiedPath.fromNative(deployedPath).basename);
  } finally {
    disk.restore();
  }
});

