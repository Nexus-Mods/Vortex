import * as nodeFs from "node:fs";
import * as path from "node:path";

import { beforeEach, describe, expect, it, vi } from "vitest";

const paths = vi.hoisted(() => ({ pluginDir: "" }));

// resolve the game's plugin directory into a per-test temp dir
vi.mock("./gameSupport", () => ({ pluginPath: () => paths.pluginDir }));

import { makeTempDir } from "../../../test-utils/tempDir";
import type { IState } from "../../../types/IState";
import { pluginListContribution } from "./pluginListContribution";

const HEADER = "# Automatically generated by Vortex\r\n";

describe("pluginListContribution", () => {
  const state = {} as IState;
  const generate = (gameMode: string) => pluginListContribution(state, gameMode, "profile-1");

  beforeEach(async () => {
    paths.pluginDir = await makeTempDir("vortex-plugin-list-");
  });

  it("declares loadorder.txt and plugins.txt with their exact bytes on disk", async () => {
    const loadOrderTxt = Buffer.from(`${HEADER}Skyrim.esm\r\nCafé.esp`, "utf8");
    const pluginsTxt = Buffer.from(`${HEADER}*Café.esp\r\n`, "latin1");
    nodeFs.writeFileSync(path.join(paths.pluginDir, "loadorder.txt"), loadOrderTxt);
    nodeFs.writeFileSync(path.join(paths.pluginDir, "plugins.txt"), pluginsTxt);

    expect(await generate("skyrimse")).toEqual([
      { destinationPath: path.join(paths.pluginDir, "loadorder.txt"), content: loadOrderTxt },
      { destinationPath: path.join(paths.pluginDir, "plugins.txt"), content: pluginsTxt },
    ]);
  });

  it("leaves out a plugin file that does not exist yet", async () => {
    const pluginsTxt = Buffer.from(`${HEADER}*Café.esp\r\n`, "latin1");
    nodeFs.writeFileSync(path.join(paths.pluginDir, "plugins.txt"), pluginsTxt);

    expect(await generate("skyrimse")).toEqual([
      { destinationPath: path.join(paths.pluginDir, "plugins.txt"), content: pluginsTxt },
    ]);
  });
});
